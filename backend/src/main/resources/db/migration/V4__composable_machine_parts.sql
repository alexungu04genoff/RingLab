CREATE TABLE machine_parts (
    id UUID PRIMARY KEY,
    source_machine_id UUID NOT NULL REFERENCES machines(id),
    part_type VARCHAR(5) NOT NULL CHECK (part_type IN ('FRONT', 'REAR', 'TIRE')),
    UNIQUE (source_machine_id, part_type)
);

